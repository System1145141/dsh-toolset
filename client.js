    /**
     * Replacement renderer for durable user messages: the official content
     * stack plus the host's copy/time row, extended with a rewind action.
     * Registered with priority -1 so it shadows the shipped `user` renderer.
     */
    function RewindUserRow({ node, renderFactorySlot, loadImage, t, sessionId, useChat, useAccess }) {
      const current = useFeatures();
      const data = node?.data ?? { content: [] };
      const parts = React.useMemo(() => contentParts(Array.isArray(data.content) ? data.content : []), [data.content]);
      const prepared = React.useMemo(
        () => ({
          text: parts.text,
          attachments: parts.attachments,
          extraBlocks: parts.rest,
          ...(data.referenceLabels === undefined ? {} : { referenceLabels: data.referenceLabels }),
        }),
        [parts, data.referenceLabels],
      );
      const facts = React.useMemo(
        () => ({
          ...(data.referenceLabels === undefined ? {} : { sessionLabels: data.referenceLabels }),
          ...(data.skillNames === undefined ? {} : { skillNames: data.skillNames }),
        }),
        [data.referenceLabels, data.skillNames],
      );

      const turnNumber = node?.location !== undefined && (node.location.kind === 'turn' || node.location.kind === 'step') ? node.location.turn.turn : undefined;
      const previousTurnEndSeq = useChat((snapshot) => {
        if (turnNumber === undefined) return undefined;
        const order = snapshot.timeline.turnOrder;
        const index = order.indexOf(turnNumber);
        if (index <= 0) return undefined;
        return snapshot.timeline.turns.get(order[index - 1])?.end?.seq;
      });
      const fallbackTarget = typeof data.seq === 'number' && data.seq > 0 ? data.seq - 1 : undefined;
      const targetSeq = previousTurnEndSeq ?? (turnNumber === undefined ? fallbackTarget : undefined);

      const forkAllowed = typeof useAccess === 'function' ? useAccess('session/fork') !== false : true;
      const [copied, setCopied] = React.useState(false);
      const [busy, setBusy] = React.useState(false);
      const [error, setError] = React.useState(null);
      const copyTimer = React.useRef(null);
      React.useEffect(
        () => () => {
          if (copyTimer.current !== null) clearTimeout(copyTimer.current);
        },
        [],
      );

      const onCopy = () => {
        if (copied || parts.text === '') return;
        void copyText(parts.text).then((ok) => {
          if (!ok) return;
          setCopied(true);
          copyTimer.current = window.setTimeout(() => {
            copyTimer.current = null;
            setCopied(false);
          }, 1200);
        });
      };

      const onRewind = () => {
        if (busy) return;
        if (targetSeq === undefined) {
          setError(t('rewind.first'));
          return;
        }
        setBusy(true);
        setError(null);
        void (async () => {
          try {
            const binding = services.sessions?.binding?.(sessionId);
            if (binding !== undefined) {
              try {
                await binding.session.cancel();
              } catch {
                // Nothing was running; the fork below still works.
              }
            }
            const childId = await services.sessions.fork({ sessionId, atSeq: targetSeq, increaseTitle: true });
            services.uiWorkspace.openSession(childId);
            // The original conversation is archived so the branch reads as the
            // rewound conversation; archived sessions remain restorable.
            window.setTimeout(() => {
              void services.uiWorkspace.archiveSession(sessionId).catch(() => {});
            }, 500);
          } catch (caught) {
            setError(t('rewind.failed', { message: caught instanceof Error ? caught.message : String(caught) }));
          } finally {
            setBusy(false);
          }
        })();
      };

      const showRewind = current[FEATURE_REWIND] !== false;
      return h(
        'div',
        { className: `${PREFIX}-userRow` },
        renderFactorySlot('conversation.chat.user.content', { content: prepared, loadImage, facts, interactive: true }),
        h(
          'div',
          { className: `${PREFIX}-userActions` },
          h('span', { className: `${PREFIX}-userTime` }, formatClockTime(data.time)),
          h(
            'button',
            {
              type: 'button',
              className: `${PREFIX}-userAction`,
              title: copied ? t('rewind.copied') : t('rewind.copy'),
              'aria-label': copied ? t('rewind.copied') : t('rewind.copy'),
              onClick: onCopy,
            },
            actionIcon(copied ? 'check' : 'copy'),
          ),
          showRewind && forkAllowed
            ? h(
                'button',
                {
                  type: 'button',
                  className: `${PREFIX}-userAction`,
                  title: t('rewind.tooltip'),
                  'aria-label': t('rewind.label'),
                  disabled: busy,
                  onClick: onRewind,
                },
                actionIcon('rewind'),
              )
            : null,
        ),
        error === null ? null : h('div', { className: `${PREFIX}-userError`, role: 'alert' }, error),
      );
    }

