    /** Split user content into text, attachments, and everything else (official shape). */
    function contentParts(content) {
      const texts = [];
      const attachments = [];
      const rest = [];
      for (const block of content) {
        const value = block;
        if (value.type === 'text' && typeof value.text === 'string') texts.push(value.text);
        else if (value.type === 'image' && value.attachment !== undefined) attachments.push({ type: 'image', image: { attachment: value.attachment } });
        else if (value.type === 'file' && value.attachment !== undefined) attachments.push({ type: 'file', file: value.attachment });
        else rest.push(block);
      }
      return { text: texts.join(''), attachments, rest };
    }

    /** Format one message timestamp like the host's own message clock. */
    function formatClockTime(time) {
      if (typeof time !== 'number') return '';
      try {
        return new Intl.DateTimeFormat(undefined, { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' }).format(new Date(time));
      } catch {
        return '';
      }
    }

    /** Copy text with the async clipboard API and a legacy fallback. */
    async function copyText(text) {
      try {
        await navigator.clipboard.writeText(text);
        return true;
      } catch {
        // Fall through to the legacy path.
      }
      try {
        const area = document.createElement('textarea');
        area.value = text;
        area.style.position = 'fixed';
        area.style.opacity = '0';
        document.body.appendChild(area);
        area.select();
        const ok = document.execCommand('copy');
        document.body.removeChild(area);
        return ok;
      } catch {
        return false;
      }
    }

